class Wire:
    def __init__(self) -> None:
        self.requests: list[HttpRequest] = []
        self.reply: dict[str, Any] = completion()
        self.status = 200
        self.headers: dict[str, str] = {}
        self.stream_frames: list[str] = []
        self.stream_status = 200

    def send(self, request: HttpRequest) -> HttpResponse:
        self.requests.append(request)
        return HttpResponse(
            status=self.status,
            body=canonical.encode(self.reply).encode("utf-8"),
            headers=self.headers,
        )

    def stream(self, request: HttpRequest) -> HttpStreamResponse:
        self.requests.append(request)
        return HttpStreamResponse(
            status=self.stream_status, headers={}, chunks=iter(self.stream_frames)
        )

    def body(self, index: int = -1) -> str:
        raw = self.requests[index].body
        assert isinstance(raw, bytes)
        return raw.decode("utf-8")


